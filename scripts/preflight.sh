#!/usr/bin/env bash
# Preflight checks before terraform apply. Read-only.
set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"

fail=0
ok()   { printf '  OK    %s\n' "$*"; }
bad()  { printf '  FAIL  %s\n' "$*"; fail=1; }

echo "Tools"
for c in terraform az jq curl; do
  if command -v "$c" >/dev/null 2>&1; then ok "$c: $("$c" --version 2>/dev/null | head -1)"; else bad "$c not installed"; fi
done

echo "Azure"
if command -v az >/dev/null 2>&1; then
  if sub="$(az account show --query '{name:name,id:id}' -o tsv 2>/dev/null)"; then
    ok "logged in: $sub"
    log "Confirm this is the intended subscription before applying."
  else
    bad "not logged in: run 'az login'"
  fi
fi

echo "Elastic Cloud"
if [ -z "${EC_API_KEY:-}" ]; then
  bad "EC_API_KEY not set"
else
  code="$(printf 'header = "Authorization: ApiKey %s"\n' "$EC_API_KEY" | \
    curl -s -o /dev/null -w '%{http_code}' -K - https://api.elastic-cloud.com/api/v1/deployments || true)"
  if [ "$code" = 200 ]; then ok "EC_API_KEY valid"; else bad "EC_API_KEY invalid (HTTP $code): create a new key in Elastic Cloud console > Organization > API keys"; fi
fi

echo "Terraform variables"
tfvars=""
for f in "$TF_DIR/terraform.tfvars" "$PROJECT_ROOT/terraform.tfvars"; do
  [ -f "$f" ] && tfvars="$f" && break
done
if [ -n "$tfvars" ]; then ok "tfvars: ${tfvars#"$PROJECT_ROOT"/}"; else bad "no terraform.tfvars (copy terraform.tfvars.example to terraform/terraform.tfvars)"; fi

ip=""
[ -n "$tfvars" ] && ip="$(sed -n 's/^[[:space:]]*presenter_ip_cidr[[:space:]]*=[[:space:]]*"\(.*\)".*/\1/p' "$tfvars" | head -1)"
ip="${ip:-${TF_VAR_presenter_ip_cidr:-}}"
if [ -z "$ip" ]; then
  bad "presenter_ip_cidr not set (tfvars or TF_VAR_presenter_ip_cidr)"
elif [ "$ip" = "203.0.113.5/32" ]; then
  bad "presenter_ip_cidr is still the example value"
elif [ "$ip" = "0.0.0.0/0" ] || [ "$ip" = "*" ]; then
  bad "presenter_ip_cidr must not be open to the internet"
else
  ok "presenter_ip_cidr set: $ip"
  mine="$(curl -s --max-time 5 https://checkip.amazonaws.com | tr -d '[:space:]' || true)"
  if [ -n "$mine" ] && [ "$ip" != "$mine/32" ]; then log "note: your current public IP is $mine; tfvars has $ip"; fi
fi

ok "vm_admin_password is generated by Terraform (random_password)"

if [ "$fail" -ne 0 ]; then echo; die "preflight failed"; fi
echo; echo "PREFLIGHT PASSED"
