#!/usr/bin/env bash
# Run the Weekly Situation Report workflow now, wait for it, and print the resulting report.
# Needs scripts/configure-reports.sh to have installed the workflow (workflow_id in shared/env.json).
# Env: RUN_TIMEOUT seconds to wait (default 300).
#      REPORT_CLIENT    only timelines for this client code, e.g. CLIENT-B (default: all)
#      REPORT_KEYWORDS  only timelines whose description has ALL these words, e.g. "true-positive" (default: any)
set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"
require_cmd jq curl
load_env

wf_id="$(env_get workflow_id)"
[ -n "$wf_id" ] || die "workflow_id missing in $ENV_FILE; run scripts/configure-reports.sh (or run the workflow from Kibana > Workflows)"
timeout_s="${RUN_TIMEOUT:-300}"

started="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
log "Running workflow $wf_id"
inputs="$(jq -nc --arg c "${REPORT_CLIENT:-}" --arg k "${REPORT_KEYWORDS:-}" '{inputs:{client:$c,keywords:$k}}')"
log "Inputs: $inputs"
resp="$(kbn POST "/api/workflows/workflow/$wf_id/run" -d "$inputs")"
exec_id="$(jq -r '.workflowExecutionId // .executionId // .id // empty' <<<"$resp" 2>/dev/null || true)"
[ -n "$exec_id" ] || die "run accepted but no execution id in the response: $(head -c 300 <<<"$resp")"
log "Execution id: $exec_id"

deadline=$(( $(date +%s) + timeout_s ))
status=""; done_ok=false
while [ "$(date +%s)" -lt "$deadline" ]; do
  st="$(try_api GET "$KIBANA_URL/api/workflows/executions/$exec_id" || true)"
  status="$(jq -r '.status // empty' <<<"$st" 2>/dev/null || true)"
  case "$status" in
    completed|COMPLETED|success|SUCCESS) done_ok=true; break ;;
    failed|FAILED|cancelled|CANCELLED|timed_out|TIMED_OUT)
      log "Execution ended with status: $status"
      try_api GET "$KIBANA_URL/api/workflows/executions/$exec_id/logs" | head -c 2000 >&2 || true
      die "workflow did not complete" ;;
  esac
  sleep 5
done
[ "$done_ok" = true ] || die "timed out after ${timeout_s}s (last status: ${status:-unreadable; check GET /api/workflows/executions/$exec_id})"

# Latest report generated by this run.
rep="$(try_api POST "$ES_URL/situation-reports/_search" \
  -d "$(jq -nc --arg s "$started" '{size:1,sort:[{generated_at:"desc"}],query:{range:{generated_at:{gte:$s}}}}')" || true)"
n="$(jq '.hits.hits | length' <<<"$rep" 2>/dev/null || echo 0)"
[ "${n:-0}" -ge 1 ] || die "workflow completed but no new document in situation-reports (check the execution logs in Kibana > Workflows)"

jq -r '.hits.hits[0]._source | "TLP: \(.tlp)  Client: \(.client)  Period: \(.period_start) to \(.period_end)\nFilters: client=\(.filter_client // "") keywords=\(.filter_keywords // "")\nKeywords: \((.keywords // []) | join(", "))\nSources: \(.sources | join("; "))\n\n\(.body)"' <<<"$rep"
