#!/usr/bin/env bash
# Import timeline template, example investigated timeline and historical timelines from
# config/timelines/*.ndjson via Kibana POST /api/timeline/_import.
#
# Idempotency: for each file, the titles it contains are compared with timelines already in
# Kibana (matched by exact title and timeline type). A file whose titles all exist is skipped.
# Set FORCE=1 to import anyway (Kibana may then reject duplicate saved-object ids with HTTP 409).
#
# Context tokens __RUN_DATE__, __HOST_NAME__, __USER_NAME__, __CLIENT__ (default CLIENT-A) are
# substituted before the title/idempotency check. Pinned-event tokens:
# tokens __PINNED_EVENT_ID_N__ (N = 1,2,...) in a file are replaced with the _id of
# the earliest alert of the N-th distinct rule in the security alerts index. This needs alerts, so
# run scripts/attack.sh first. Files containing tokens are SKIPPED (with a message) when no alerts
# exist yet; re-run this script after the attack. If config/README.md documents other tokens,
# extend SUBST below.
set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"
load_env

TL_DIR="$CONFIG_DIR/timelines"
[ -d "$TL_DIR" ] || die "$TL_DIR not found (generated by the config step)"
shopt -s nullglob
files=("$TL_DIR"/*.ndjson)
[ "${#files[@]}" -gt 0 ] || die "no .ndjson files in $TL_DIR"

# Existing timelines as "type<TAB>title" lines.
existing=""
fetch_existing() {
  local body
  body="$(try_api GET "${KIBANA_URL}/api/saved_objects/_find?type=siem-ui-timeline&per_page=1000" || true)"
  if [ -n "$body" ] && printf '%s' "$body" | jq -e '.saved_objects' >/dev/null 2>&1; then
    existing="$(printf '%s' "$body" | jq -r '.saved_objects[] | [(.attributes.timelineType // "default"), .attributes.title] | @tsv')"
    return
  fi
  body="$(try_api GET "${KIBANA_URL}/api/timelines?page_size=1000&page_index=1" || true)"
  if [ -n "$body" ] && printf '%s' "$body" | jq -e '.timeline' >/dev/null 2>&1; then
    existing="$(printf '%s' "$body" | jq -r '.timeline[] | [(.timelineType // "default"), .title] | @tsv')"
    return
  fi
  log "warning: could not list existing timelines; idempotency check disabled"
}
fetch_existing

# Alert ids for token substitution (lazy).
alert_ids=""
alert_ids_loaded=false
load_alert_ids() {
  [ "$alert_ids_loaded" = true ] && return
  alert_ids_loaded=true
  local body
  body="$(try_api POST "${ES_URL}/.alerts-security.alerts-*/_search" \
    -d '{"size":50,"_source":false,"sort":[{"@timestamp":"asc"}],"collapse":{"field":"kibana.alert.rule.name"}}' || true)"
  alert_ids="$(printf '%s' "$body" | jq -r '.hits.hits[]?._id' 2>/dev/null || true)"
}

imported=0; skipped=0; deferred=0
tmpdir="$(mktemp -d)"; trap 'rm -rf "$tmpdir"' EXIT

for f in "${files[@]}"; do
  name="$(basename "$f")"
  out="$tmpdir/$name"
  cp "$f" "$out"

  # Substitute run-context tokens first, so titles can be compared with what is already in Kibana.
  # Override with RUN_DATE, HOST_NAME, USER_NAME, CLIENT.
  run_date="${RUN_DATE:-$(date -u +%Y-%m-%d)}"
  # host.name in the events is the Windows computer name, which differs from the Azure resource
  # name (vm_name). Use the most common host.name in the security alerts, else in the endpoint
  # events, so the queries match even when the import runs before any alert exists.
  if [ -z "${HOST_NAME:-}" ] && [ -z "${detected_host:-}" ]; then
    for idx in ".alerts-security.alerts-*" "logs-endpoint.events.*"; do
      detected_host="$(try_api POST "${ES_URL}/${idx}/_search" \
        -d '{"size":0,"aggs":{"h":{"terms":{"field":"host.name","size":1}}}}' \
        | jq -r '.aggregations.h.buckets[0].key // empty' 2>/dev/null || true)"
      [ -n "$detected_host" ] && break
    done
    detected_host="${detected_host:-none}"
  fi
  [ "${detected_host:-none}" = none ] && detected_host=""
  host_name="${HOST_NAME:-${detected_host:-$(env_get vm_name)}}"; host_name="${host_name:-demo-vm}"
  user_name="${USER_NAME:-$(env_get vm_admin_username)}"; user_name="${user_name:-demoadmin}"
  client="${CLIENT:-CLIENT-A}"
  sed -i.bak \
    -e "s|__RUN_DATE__|${run_date}|g" \
    -e "s|__HOST_NAME__|${host_name}|g" \
    -e "s|__USER_NAME__|${user_name}|g" \
    -e "s|__CLIENT__|${client}|g" "$out"; rm -f "$out.bak"

  # Kibana 9.5 validates every line as a timeline, so the trailing export summary line
  # ({"exportedCount": ...}) makes the import fail. Keep only timeline objects.
  jq -c 'select(type=="object" and .title != null)' "$out" > "$out.tl" && mv "$out.tl" "$out"

  # Skip if every title in the file already exists.
  if [ "${FORCE:-0}" != 1 ] && [ -n "$existing" ]; then
    missing="$(jq -r 'select(type=="object" and .title != null) | [(.timelineType // "default"), .title] | @tsv' "$out" \
      | while IFS= read -r line; do printf '%s\n' "$existing" | grep -Fxq -- "$line" || echo "$line"; done)"
    if [ -z "$missing" ]; then
      log "skip $name (all timelines already present)"; skipped=$((skipped+1)); continue
    fi
  fi

  # Substitute __PINNED_EVENT_ID_N__ tokens (needs alerts, so run scripts/attack.sh first).
  tokens="$(grep -o '__PINNED_EVENT_ID_[0-9]*__' "$out" | sort -u || true)"
  if [ -n "$tokens" ]; then
    load_alert_ids
    if [ -z "$alert_ids" ]; then
      log "defer $name (needs alerts for pinned event ids; run scripts/attack.sh, then re-run)"
      deferred=$((deferred+1)); continue
    fi
    for t in $tokens; do
      n="${t//[!0-9]/}"
      id="$(printf '%s\n' "$alert_ids" | sed -n "${n}p")"
      [ -n "$id" ] || id="$(printf '%s\n' "$alert_ids" | head -1)"   # fewer alerts than tokens: reuse the first
      sed -i.bak "s|${t}|${id}|g" "$out"; rm -f "$out.bak"
    done
  fi

  log "import $name"
  resp="$(api POST "${KIBANA_URL}/api/timeline/_import" -F "file=@${out};type=application/x-ndjson" -F "isImmutable=false")" \
    || die "import of $name failed"
  errs="$(printf '%s' "$resp" | jq -c '.errors // [] | length' 2>/dev/null || echo 0)"
  if [ "$errs" != 0 ]; then
    printf '%s\n' "$resp" | jq -c '.errors' | head -c 800 >&2; echo >&2
    die "Kibana reported import errors for $name (if duplicates, delete the timelines or adjust ids)"
  fi
  imported=$((imported+1))
done

echo "TIMELINES: imported=$imported skipped=$skipped deferred=$deferred"
